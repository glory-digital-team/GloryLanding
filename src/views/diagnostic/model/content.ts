// Тексты страницы «Бесплатная диагностика». В реестр pages.data.ts не входят:
// он генерируется из «ядро.xlsx» и руками не правится. После добавления страницы
// в реестр тексты можно перенести туда.
//
// Правило: всё, что не подтверждено заказчиком (формат, сроки, число мест, цифры),
// помечается `confirmed: false` с текстом `[UNCONFIRMED: …]` и на сайт не выводится.

export interface Draft<T> {
  value: T;
  confirmed: boolean;
}

/** Только подтверждённые значения: неподтверждённые в прод не попадают. */
export function confirmedOnly<T>(items: Draft<T>[]): T[] {
  return items.filter((item) => item.confirmed).map((item) => item.value);
}

